// Export public, reviewed mini-program records only. Never copy user/GPS storage.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createRequire } = require('node:module');
const source = path.resolve(process.argv[2] || '../WeChatProjects/miniprogram-1');
const output = path.resolve(__dirname, '..');
const file = path.join(source, 'miniprogram/pages/index/index.js');
const context = vm.createContext({ require: createRequire(file), Page() {}, wx: {},
  getApp: () => ({ globalData: {} }), setTimeout, clearTimeout, setInterval, clearInterval });
vm.runInContext(fs.readFileSync(file, 'utf8'), context);
const read = expression => vm.runInContext(expression, context);
const coordinates = require('../assets/campus_coordinates.js');
const facilities = require(path.join(source, 'miniprogram/data/campusFacilities.js'));
const courseLocations = read('COURSE_ROOM_LOCATIONS');
const pois = read('MAP_DATA.pois');
const items = facilities.items.map(item => {
  const resolved = facilities.resolve(item, courseLocations, pois);
  return { ...resolved, webCoord: resolved.coord ? coordinates.toWgs84(resolved.coord) : null };
});
const icons = {};
for (const theme of ['light', 'dark']) {
  icons[theme] = {};
  const folder = path.join(source, 'miniprogram/assets/facilities', theme);
  for (const icon of fs.readdirSync(folder).filter(name => name.endsWith('.png')).sort()) {
    icons[theme][path.basename(icon, '.png')] = 'data:image/png;base64,' + fs.readFileSync(path.join(folder, icon)).toString('base64');
  }
}
const atlas = require(path.join(source, 'miniprogram/data/campusAtlas.js'));
const unproject = ([x,y]) => coordinates.toWgs84([x*360-180, Math.atan(Math.sinh(Math.PI*(1-2*y)))*180/Math.PI]);
for (const theme of ['light', 'dark']) fs.copyFileSync(path.join(source, 'miniprogram/assets/basemap', `campus-${theme}.png`), path.join(output, 'assets', `campus-${theme}.png`));
const data = { version: '20261026.5', checkedAt: facilities.checkedAt,
  basemap: { bounds:[unproject([atlas.bounds[0],atlas.bounds[3]]).reverse(),unproject([atlas.bounds[2],atlas.bounds[1]]).reverse()],
    labels:atlas.labels.map(label => ({ name:label.name, coord:unproject(label.point), area:label.size })) },
  sources: facilities.sources, categories: facilities.categories, items, icons,
  buildings: Object.values(courseLocations).map(item => ({ ...item, offCampus: ['BATC', 'HKSP', 'MED'].includes(item.shortName),
    webCoord: item.coord ? coordinates.toWgs84(item.coord) : null })),
  dining: read('allDiningPois()').filter(item => ['restaurant', 'fast_food', 'coffee', 'tea'].includes(item.category))
    .map(item => ({ ...item, hidden: !!item.hiddenByDefault || read(`poiDefaultHiddenByStatus(${JSON.stringify(item)})`), webCoord: item.coord ? coordinates.toWgs84(item.coord) : null,
      aliases: Array.from(read(`knownPoiSearchAliases(${JSON.stringify(item)})`)) })),
};
const normalizers = ['normalizePlaceSearchText', 'normalizeCourseSearchText', 'toSimplifiedSearchText']
  .map(name => read(name + '.toString()')).join('\n');
fs.writeFileSync(path.join(output, 'data/campus_guide.js'),
  '// Generated by scripts/sync_campus_guide.js; public mini-program data, GCJ-02 + WGS84.\n' +
  '(function(root) {\nconst data = ' + JSON.stringify(data) + ';\n' + normalizers +
  '\ndata.normalize = normalizePlaceSearchText;\n' + facilities.hoursFor.toString() +
  '\ndata.hoursFor = hoursFor;\nroot.CUHK_CAMPUS_GUIDE = data;\n' +
  'if (typeof module !== "undefined") module.exports = data;\n})(globalThis);\n');
const helpers = ['walkingRouteBetweenCoords', 'walkingGraphRuntime', 'walkingGraphComponents',
  'walkingGraphSnapPair', 'bestWalkingGraphSnapPair', 'nearestWalkingGraphPointCandidates',
  'shortestWalkingGraphPath', 'walkingGraphNeighbors', 'walkingGraphCoordForNode',
  'sameWalkingGraphSegment', 'pushWalkingHeap', 'popWalkingHeap', 'cacheWalkingRoute',
  'routePlanCoordKey', 'projectCoordToSegment', 'interpolateRoutePlanCoord',
  'uniqueRoutePlanCoords', 'validRoutePlanCoord', 'routePlanPathDistance', 'distanceMetersBetween', 'toRad'];
const constants = ['WALKING_ROUTE_MAX_SNAP_METERS', 'WALKING_ROUTE_MAX_DETOUR_RATIO',
  'WALKING_ROUTE_CACHE_LIMIT', 'WALKING_ROUTE_ALGORITHM_VERSION'];
fs.writeFileSync(path.join(output, 'data/campus_walking.js'),
  '// Generated from the tested mini-program walking engine. Loaded only for navigation.\n' +
  '(function(root) {\nconst WALKING_GRAPH = ' + JSON.stringify(read('WALKING_GRAPH')) + ';\n' +
  constants.map(name => 'const ' + name + ' = ' + JSON.stringify(read(name)) + ';').join('\n') +
  '\nconst walkingRouteCache = {}, walkingRouteCacheKeys = [];\n' +
  helpers.map(name => read(name + '.toString()')).join('\n') +
  '\nconst api = { route: walkingRouteBetweenCoords, distance: distanceMetersBetween };\n' +
  'root.CUHK_CAMPUS_WALKING = api;\nif (typeof module !== "undefined") module.exports = api;\n})(globalThis);\n');
console.log(`Synced ${items.length} facilities, ${data.buildings.length} buildings, ${data.dining.length} dining records, ${Object.keys(icons.light).length * 2} icons.`);
